"""Published coefficients for the Hardy et al. (1991) ion model.

The values below are a direct transcription of Table 1 in:

    Hardy, D. A., McNeil, W., Gussenhoven, M. S., and Brautigam, D. (1991),
    A statistical model of auroral ion precipitation: 2. Functional
    representation of the average patterns, JGR, 96(A4), 5539--5547.
    https://doi.org/10.1029/90JA02451

No model equations are implemented here. This module only records the table;
the equations that use it are kept in ``hardy.py``.

Array layout
------------
Both coefficient arrays have shape ``(7, 13, 6)``:

``[Kp level, Fourier coefficient, Epstein parameter]``

The axes are described by ``KP_LEVELS``, ``FOURIER_TERMS``, and
``EPSTEIN_PARAMETERS``. The 13 rows are ``c0``, six cosine coefficients, and
six sine coefficients. The six columns are ``r0, h0, h1, S0, r1, S2``.

``r0`` and ``r1`` are log10 integral fluxes, ``h0`` and ``h1`` are corrected
geomagnetic latitudes in degrees, and ``S0`` and ``S2`` are log10-flux slopes
per degree. Before taking log10, integral number flux is measured in
``ions cm^-2 s^-1 sr^-1`` and integral energy flux in
``keV cm^-2 s^-1 sr^-1``.
"""

